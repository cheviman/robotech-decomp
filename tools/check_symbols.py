"""symbols/symbols.txt against itself: what a round of merged proposals can leave wrong without a build.

    py -3.14 tools/check_symbols.py

Tells, and hands back 1 if it tells anything:
- a line of the hand sections that starts as a symbol line and is read as none (a field's size written in
  hexadecimal, `u8[2C]`: tools/symbols.py reads array sizes in decimal and skips the line);
- an array size of digits alone that fits its place only when read as hexadecimal (`u8[3700]` for 0x3700);
- two variables that cover the same address (a variable is as long as its type);
- two fields of a structure that cover the same offset, and a field that ends past its structure's size;
- a function's address or a variable's with two lines by hand, a name for two things, a function with two
  comments by hand, a structure declared twice.
"""
import bisect
import collections
import os
import re
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import symbols as S

UNIT = {"u8": 1, "s8": 1, "char": 1, "u16": 2, "s16": 2, "u32": 4, "s32": 4, "f32": 4, "f64": 8}
ADDR = re.compile(r"^[0-9A-Fa-f]{8}$")


def main():
    told = 0

    def tell(text):
        nonlocal told
        told += 1
        if told <= 60:
            print(text)

    sym = S.load()
    generated = False
    funcs, variables, comments, structs = (collections.defaultdict(list) for _ in range(4))
    names = collections.defaultdict(set)
    for n, l in enumerate(open(S.SYMBOLS, encoding="utf-8").read().split("\n"), 1):
        if l.startswith("# ========"):
            generated = "(generated by" in l
        f = l.partition("#")[0].split()
        if not f:
            continue
        if len(f) >= 3 and ADDR.match(f[0]) and f[1] in ("func", "var"):
            names[f[2]].add((f[1], f[0].upper()))
        if generated:
            continue
        starts = f[0] in ("field", "struct", "type", "param", "local", "comment") or \
            (len(f) > 1 and ADDR.match(f[0]) and f[1] in ("func", "var", "data", "file"))
        if starts and not S.entries([l]):
            tell("line %d is read as nothing: %s" % (n, l[:100]))
        if len(f) >= 3 and ADDR.match(f[0]) and f[1] == "func":
            funcs[f[0].upper()].append(n)
        elif len(f) >= 3 and ADDR.match(f[0]) and f[1] == "var":
            variables[f[0].upper()].append(n)
        elif f[0] == "comment" and len(f) >= 2:
            comments[f[1]].append(n)
        elif f[0] == "struct" and len(f) == 3:
            structs[f[1]].append(n)
    for what, d in (("function at", funcs), ("variable at", variables), ("comment of", comments), ("struct", structs)):
        for key, where in d.items():
            if len(where) > 1:
                tell("%s %s on lines %s" % (what, key, ", ".join(map(str, where))))
    for name, things in names.items():
        if len(things) > 1:
            tell("the name %s for %s" % (name, ", ".join("%s %s" % t for t in sorted(things))))

    def length(type_name):
        m = re.match(r"^(\w+?)(?:\[(\d*)\])?$", type_name)
        count = int(m.group(2)) if m.group(2) else 1
        return max(1, (UNIT.get(m.group(1)) or sym["structs"].get(m.group(1), {}).get("size", 4)) * count)

    spans = sorted((a, a + length(v["type"]), v["name"]) for a, v in sym["vars"].items())
    for (a, end, name), (b, _, other) in zip(spans, spans[1:]):
        if b < end:
            tell("variables overlap: %s 0x%X..0x%X and %s at 0x%X" % (name, a, end, other, b))
    for name, st in sorted(sym["structs"].items()):
        if not st.get("size"):
            tell("struct %s has fields and no struct line" % name)
            continue
        fields = []
        for f in st["fields"]:
            m = S.TYPE_RE.match(f["type"])
            fields.append((f["offset"], UNIT[m.group(1)], int(m.group(2)) if m.group(2) else 1, f["name"], m.group(2)))
        fields.sort()
        ends = [x[0] for x in fields[1:]] + [st["size"]]
        for (off, unit, count, field, written), limit in zip(fields, ends):
            if off + unit * count > limit:
                tell("%s.%s at +0x%X is 0x%X long and the next thing is at +0x%X" % (name, field, off, unit * count, limit))
            elif written and written.isdigit() and int(written, 16) != count and off + unit * int(written, 16) == limit:
                tell("%s.%s at +0x%X: [%s] ends at the next thing (+0x%X) only read as hexadecimal" % (name, field, off, written, limit))
    print("%d structures, %d variables, %d functions: %d told" % (len(sym["structs"]), len(sym["vars"]), len(sym["func"]), told))
    sys.exit(1 if told else 0)


if __name__ == "__main__":
    main()
