"""Review tasks, then the merge of a naming wave into symbols/symbols.txt.

    py -3 tools/naming/merge_names.py WAVE review    writes names/WAVE/review.jsonl for the drafts that name something
    py -3 tools/naming/merge_names.py WAVE merge     puts the reviewed names into symbols.txt (OK as drafted,
                                                 BETTER with the reviewer's name, WRONG left out)
A name given to two functions, or already another symbol's, is left out for the next wave.
"""
import json, os, re, sys, collections

REPO = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
wave, what = sys.argv[1], sys.argv[2]
D = os.path.join(REPO, "build", "cr", "names", wave)
SYM = os.path.join(REPO, "symbols", "symbols.txt")
LINE = re.compile(r"^\s*`?(?:0x)?([0-9A-Fa-f]{8})\s+(\S+)\s+(.*?)`?\s*$")

def drafts():
    for f in sorted(os.listdir(D)):
        if re.match(r"^t\d+\.txt$", f):
            yield f[:-4], os.path.join(D, f)

if what == "review":
    with open(os.path.join(D, "review.jsonl"), "w", newline="\n") as fh:
        for t, p in drafts():
            named = [m for m in map(LINE.match, open(p, encoding="utf-8").read().split("\n")) if m and m.group(2) != "skip"]
            if not named or os.path.exists(p + ".check.txt"):
                continue
            rel = lambda x: os.path.relpath(x, REPO).replace("\\", "/")
            fh.write(json.dumps({"id": "%s-%s-rev" % (wave, t), "prompt": "Review the draft as the instructions above say.",
                                 "files": [rel(os.path.join(D, t + ".c")), rel(p)], "out": rel(os.path.join(D, t + ".rev.txt")),
                                 "check": "py -3 tools/naming/check_review.py {out} " + rel(p),
                                 "max_tokens": 4000 + 300 * len(named), "effort": "low"}) + "\n")
    sys.exit(0)

text = open(SYM, encoding="utf-8").read()
taken = set()
for t in text.split("\n"):
    p = t.split()
    if len(p) >= 3 and re.match(r"^[0-9A-F]{8}$", p[0]):
        taken.add(p[2])
    elif len(p) >= 3 and p[0] in ("struct", "comment"):
        taken.add(p[1])
got, stats = {}, collections.Counter()
for t, p in drafts():
    rp = os.path.join(D, t + ".rev.txt")
    verdict = {}
    if os.path.exists(rp) and not os.path.exists(rp + ".check.txt"):
        for l in open(rp, encoding="utf-8").read().split("\n"):
            m = re.match(r"^\s*`?(?:0x)?([0-9A-Fa-f]{8})\s+(OK|BETTER|WRONG)\b\s*(\S*)", l)
            if m:
                verdict[m.group(1).upper()] = (m.group(2), m.group(3))
    for l in open(p, encoding="utf-8").read().split("\n"):
        m = LINE.match(l)
        if not m:
            continue
        a, nm, d = m.group(1).upper(), m.group(2), m.group(3)
        if nm == "skip":
            stats["skipped"] += 1
            continue
        v = verdict.get(a)
        if not v:
            stats["not reviewed"] += 1
            continue
        if v[0] == "WRONG":
            stats["wrong"] += 1
            continue
        if v[0] == "BETTER":
            stats["better"] += 1
            nm = v[1]
        else:
            stats["ok"] += 1
        got[a] = (nm, d)
count = collections.Counter(nm for nm, _ in got.values())
keep = {a: v for a, v in got.items() if count[v[0]] == 1 and v[0] not in taken}
stats["clash"] = len(got) - len(keep)
if not keep:
    sys.exit("nothing to merge: %s" % dict(stats))
ren = {"sub_" + a: v[0] for a, v in keep.items()}
sub = re.compile(r"\bsub_[0-9A-F]{8}\b")
out = ["# ======== functions named from their decompiled C (%s; drafted by deepseek-v4.1-flash, reviewed by gpt-6-luna) ========" % wave]
for a in sorted(keep, key=lambda x: int(x, 16)):
    nm, d = keep[a]
    d = sub.sub(lambda m: ren.get(m.group(0), m.group(0)), d).replace("_entry", "")
    out.append("%s  func  %s" % (a, nm))
    out.append("comment %s %s" % (nm, d))
marker = "# ======== the engine's classes (generated by"
i = text.index(marker)
open(SYM, "w", encoding="utf-8", newline="\n").write(text[:i] + "\n".join(out) + "\n\n" + text[i:])
print(dict(stats), "named:", len(keep))
