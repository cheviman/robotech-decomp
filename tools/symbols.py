"""
Name:        symbols.py
Description: symbols/symbols.txt, the one place the names, descriptions and files of the C live
Version:     0.1.0
Created:     25-10-2026
Modified:    26-10-2026
Author:      Sebastian Toyos

symbols/symbols.txt holds, by address, every name the C gets (functions and
data), a description of each function, and the files the functions are laid
out in. The format follows SegaSonic's symbols.txt:

    ADDRESS  func  NAME        # comment
    ADDRESS  data  NAME        # comment
    ADDRESS  file  PATH        # what the stretch holds
    comment  NAME  text

A file line sends the functions from its address up to the next file line
to src/recomp/gen/PATH.c. Sections headed "# ======== TITLE (generated by
...) ========" are rewritten by this tool from the other tools' findings;
every other line is written by hand, and a name given by hand wins over a
generated one for the same address.

    py -3 tools/symbols.py merge     # rewrite the generated name sections
    py -3 tools/symbols.py layout    # rewrite the generated file section
    py -3 tools/symbols.py header    # src/recomp/gen/symbols.h, the structures and variables for src/game/

Besides functions and files it holds what the C written by hand reads and
writes, in SegaSonic's terms:

    ADDRESS  var  NAME  TYPE [STRUCT]       a variable (TYPE u8 s8 u16 s16 u32 s32 f32 f64 char,
                                            TYPE[N] an array, TYPE[] one of unknown length; STRUCT
                                            says a u32 points at one)
    struct  NAME  SIZE                      a structure (SIZE in hexadecimal)
    field   STRUCT  OFFSET  NAME  TYPE [STRUCT]   one of its fields (OFFSET in hexadecimal)

The name sections come from symbols/lib_matches.json (tools/match_libs.py),
symbols/xdk_symbols.json (XbSymbolDatabase) and symbols/classes.json
(tools/find_classes.py). A name the host's toolchain also defines -- the
toolkit's runtime, or the names xboxrecomp's recompiler reserves (C keywords,
the C runtime, Win32 exports; its lifter's _FUNC_RESERVED_IDENT) -- takes its
library's prefix here (xapi_CreateThread), so the recompiler never adds an
address to it.
"""
import argparse
import collections
import glob
import json
import os
import re
import sys

REPO = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
SYMBOLS = os.path.join(REPO, "symbols", "symbols.txt")
LIB = os.path.join(REPO, "symbols", "lib_matches.json")
XDK = os.path.join(REPO, "symbols", "xdk_symbols.json")
CLASSES = os.path.join(REPO, "symbols", "classes.json")
REGISTRIES = os.path.join(REPO, "symbols", "registries.json")
FUNCS = os.path.join(REPO, "analysis", "disasm", "functions.json")
ANALYSIS_JSON = os.path.join(REPO, "analysis", "default_analysis.json")

IDENT = re.compile(r"^[A-Za-z_][A-Za-z0-9_]*$")
SECTION = re.compile(r"^# ======== (.*?) ========\s*$")
# names whose subject is their prefix (the first that fits)
NAME_SUBJECTS = [("vcRegisterClass", "engine/objects"), ("vcObject", "engine/objects"),
                 ("vcDefault_", "engine/objects"), ("vcClass", "engine/objects")]
FAMILY_FOLDER = {"Entity": "entities", "Effect": "effects", "Weapon": "weapons", "Screen": "screens",
                 "Action": "actions", "ScreenElement": "screen_elements", "Node": "nodes",
                 "Steering": "steering", "Trigger": "triggers", "Item": "items"}
LIB_PREFIX = {"XAPILIB": "xapi_", "D3D8": "d3d_", "DSOUND": "dsound_", "LIBCMT": "crt_",
              "LIBCPMT": "crt_", "XBOXKRNL": "krnl_"}

HEADER = """\
# Robotech: Battlecry (Xbox, XDK 4721) - the symbols of default.xbe
#
# Addresses and names only: no game data or code lives in this file. tools/symbols.py reads and writes
# it; tools/apply_names.py puts the names into the disassembly, the recompiler emits them, and
# tools/organize_gen.py lays the C out in files with each function's description.
#
# Format:  ADDRESS  KIND  NAME  [# comment]
#   ADDRESS  the Xbox virtual address, 8 hexadecimal digits
#   KIND     func = a function's entry, data = a variable or table
#   ADDRESS  file  PATH  [# what the stretch holds]
#            the functions from ADDRESS up to the next file line go to src/recomp/gen/PATH.c; a file may
#            take several stretches, and the comment of its first line describes it
#   comment  NAME  text
#            what the function NAME does, in the game's terms and with the C's names
#   ADDRESS  var  NAME  TYPE [STRUCT]
#            a variable: TYPE u8 s8 u16 s16 u32 s32 f32 f64 char, TYPE[N] an array of N, TYPE[] one of
#            unknown length; a STRUCT after a u32 says it points at one
#   struct  NAME  SIZE                     a structure of the game (SIZE in hexadecimal)
#   field   STRUCT  OFFSET  NAME  TYPE [STRUCT]
#            one of its fields (OFFSET in hexadecimal); a field nobody has named is not listed
#
# A name is real -- it says what the thing is -- or there is none: a type's number, a slot's offset or an
# address is not a name (tools/noise_report.py counts any that reaches the C).
#
# Sections headed "(generated by ...)" are rewritten by tools/symbols.py; every other line is written by
# hand, and a hand line wins over a generated one for the same address.
"""


# ── Reading and writing ─────────────────────────────────────

def parse(path=SYMBOLS):
    """The file as sections: [(title or None, [lines])], in order."""
    sections = [(None, [])]
    if not os.path.exists(path):
        return sections
    for line in open(path, encoding="utf-8"):
        line = line.rstrip("\n")
        m = SECTION.match(line)
        if m:
            sections.append((m.group(1), []))
        else:
            sections[-1][1].append(line)
    return sections


def is_generated(title):
    return bool(title) and "(generated by" in title


TYPES = {"u8": "uint8_t", "s8": "int8_t", "u16": "uint16_t", "s16": "int16_t", "u32": "uint32_t",
         "s32": "int32_t", "f32": "float", "f64": "double", "char": "char"}
TYPE_RE = re.compile(r"^(u8|s8|u16|s16|u32|s32|f32|f64|char)(?:\[(\d*)\])?$")


def entries(lines):
    """The func, data, var and file lines, the struct and field lines and the
    comment lines among lines."""
    out = []
    for line in lines:
        body, _, note = line.partition("#")
        f = body.split()
        note = note.strip()
        if len(f) >= 3 and f[0] == "comment":
            out.append({"kind": "comment", "name": f[1], "text": line.split(None, 2)[2].strip()})
        elif len(f) == 3 and f[0] == "struct":
            out.append({"kind": "struct", "name": f[1], "size": int(f[2], 16), "note": note})
        elif len(f) in (5, 6) and f[0] == "field" and TYPE_RE.match(f[4]):
            out.append({"kind": "field", "struct": f[1], "offset": int(f[2], 16), "name": f[3], "type": f[4],
                        "points": f[5] if len(f) == 6 else None, "note": note})
        elif len(f) in (4, 5) and re.match(r"^[0-9A-Fa-f]{8}$", f[0]) and f[1] == "var" and TYPE_RE.match(f[3]):
            out.append({"kind": "var", "address": int(f[0], 16), "name": f[2], "type": f[3],
                        "points": f[4] if len(f) == 5 else None, "note": note})
        elif len(f) >= 3 and re.match(r"^[0-9A-Fa-f]{8}$", f[0]) and f[1] in ("func", "data", "file"):
            out.append({"kind": f[1], "address": int(f[0], 16), "name": f[2], "note": note})
    return out


def load(path=SYMBOLS):
    """{"func": {addr: name}, "data": {addr: name}, "files": [(addr, path, note)],
    "comments": {name: text}, "hand": set of addresses named by hand}."""
    out = {"func": {}, "data": {}, "files": [], "comments": {}, "hand": set(), "structs": {}, "vars": {}}
    for title, lines in parse(path):
        for e in entries(lines):
            if e["kind"] == "comment":
                out["comments"][e["name"]] = e["text"]
            elif e["kind"] == "file":
                out["files"].append((e["address"], e["name"], e["note"]))
            elif e["kind"] == "struct":
                out["structs"].setdefault(e["name"], {"fields": []}).update(size=e["size"], note=e["note"])
            elif e["kind"] == "field":
                out["structs"].setdefault(e["struct"], {"fields": [], "size": 0, "note": ""})["fields"].append(e)
            elif e["kind"] == "var":
                out["vars"][e["address"]] = e
                out["data"][e["address"]] = e["name"]
                out["hand"].add(e["address"])
            else:
                table = out[e["kind"]]
                if not is_generated(title):
                    out["hand"].add(e["address"])
                    table[e["address"]] = e["name"]
                elif e["address"] not in out["hand"]:
                    table.setdefault(e["address"], e["name"])
    out["files"].sort()
    return out


def write(sections, path=SYMBOLS):
    with open(path, "w", encoding="utf-8", newline="\n") as f:
        first = True
        for title, lines in sections:
            if title is not None:
                f.write("# ======== %s ========\n" % title)
            while lines and not lines[-1].strip():
                lines = lines[:-1]
            for line in lines:
                f.write(line + "\n")
            f.write("\n")


def replace_section(sections, title, lines):
    """sections with the generated section `title` set to lines (added
    before the first generated name section if new)."""
    key = title.split(" (generated by")[0]
    for i, (t, _) in enumerate(sections):
        if t and t.split(" (generated by")[0] == key:
            sections[i] = (title, lines)
            return sections
    sections.append((title, lines))
    return sections


def line(addr, kind, name, note=""):
    s = "%08X  %-4s  %-34s" % (addr, kind, name)
    return (s + "  # " + note) if note else s.rstrip()


# ── merge: the tools' names ─────────────────────────────────

def toolkit_clashes(toolkit, names):
    """Names the toolkit's runtime defines or its recompiler reserves."""
    found = set()
    pats = {n: re.compile(r"^[A-Za-z_][\w \*]*\b" + re.escape(n) + r"\s*\(", re.M) for n in names}
    for p in glob.glob(os.path.join(toolkit, "src", "**", "*.[ch]"), recursive=True):
        text = open(p, encoding="latin1").read()
        for n, pat in pats.items():
            if n not in found and n in text and pat.search(text):
                found.add(n)
    sys.path.insert(0, toolkit)
    from tools.recomp.lifter import _FUNC_RESERVED_IDENT
    return found | (set(names) & _FUNC_RESERVED_IDENT)


def merge(toolkit):
    sections = parse()
    if sections == [(None, [])]:
        sections = [(None, HEADER.splitlines())]
    hand = load()["hand"]

    # (address, name, library, note), later sources winning
    found = {}
    if os.path.exists(LIB):
        for s in json.load(open(LIB)):
            how = {"bytes": "matched by bytes", "reloc": "named by a relocation", "calls": "by its place in a"
                   " caller's calls", "likeness": "by likeness of instructions"}[s["how"]]
            note = "%s %s, %s" % (s["library"], s.get("object", ""), how)
            kind = "func" if s["kind"] == "function" else "data"
            found[(kind, int(s["address"], 16))] = (s["name"], s["library"], re.sub(r"\s+", " ", note))
    if os.path.exists(XDK):
        for s in json.load(open(XDK)):
            if s["kind"] == "function":
                found[("func", int(s["address"], 16))] = (s["name"], s["library"],
                                                          "%s, found by XbSymbolDatabase" % s["library"])
    classes = []
    if os.path.exists(CLASSES):
        for s in json.load(open(CLASSES))["names"]:
            note = "%s's %s" % (s["class"], "slot +" + s["slot"][2:] if "slot" in s else "registration")
            classes.append((int(s["address"], 16), s["name"], note))

    clash = toolkit_clashes(toolkit, {v[0] for v in found.values()})
    lib_lines, data_lines, problems = [], [], []
    names_seen = collections.Counter()
    for (kind, addr), (name, library, note) in found.items():
        if name in clash:
            name = LIB_PREFIX.get(library, "xdk_") + name
        found[(kind, addr)] = (name, library, note)
        names_seen[name] += 1
    for (kind, addr), (name, library, note) in sorted(found.items(), key=lambda kv: kv[0][1]):
        if addr in hand or any(a == addr for a, _, _ in classes):
            continue
        if not IDENT.match(name) or names_seen[name] > 1:
            problems.append("%08X %s" % (addr, name))
            continue
        (lib_lines if kind == "func" else data_lines).append(line(addr, kind, name, note))
    class_lines = [line(a, "func", n, note) for a, n, note in sorted(classes) if a not in hand]

    replace_section(sections, "the engine's classes (generated by tools/symbols.py merge from "
                    "symbols/classes.json)", class_lines)
    replace_section(sections, "the XDK's functions (generated by tools/symbols.py merge from "
                    "symbols/lib_matches.json and symbols/xdk_symbols.json)", lib_lines)
    replace_section(sections, "the XDK's variables (generated by tools/symbols.py merge from "
                    "symbols/lib_matches.json)", data_lines)
    write(sections)
    print("merged: %d engine class functions, %d XDK functions, %d XDK variables; %d given their library's"
          " prefix for clashing with the toolkit" % (len(class_lines), len(lib_lines), len(data_lines),
                                                       len(clash)))
    for p in problems:
        print("  left out (not an identifier, or the same name twice): %s" % p)


# ── layout: the files ───────────────────────────────────────

def subjects():
    """{address: subject path} for the functions whose subject is known."""
    analysis = json.load(open(ANALYSIS_JSON))
    funcs = json.load(open(FUNCS))
    names = load()["func"]
    out = {}
    section_path = {"D3D": "xdk/d3d8", "DSOUND": "xdk/dsound", "XPP": "xdk/xapi_usb"}
    for f in funcs:
        a = int(f["start"], 16)
        sec = f["section"]
        if sec in section_path:
            out[a] = section_path[sec]
        elif sec.startswith("BINK"):
            out[a] = "bink/" + sec.lower()
        else:
            n = names.get(a, "")
            if n.startswith("crt_"):
                out[a] = "xdk/crt"
            elif n.startswith(("xapi_", "krnl_")) or n in ("xbe_entry_point",):
                out[a] = "xdk/xapi"
    # Names that say their subject.
    for a, n in names.items():
        for prefix, path in NAME_SUBJECTS:
            if n.startswith(prefix):
                out.setdefault(a, path)
                break
    # A function of a class or of a registry type belongs to it; one that two
    # classes or types share (a default callback) belongs to neither.
    owners = collections.defaultdict(set)
    if os.path.exists(CLASSES):
        for c in json.load(open(CLASSES))["classes"]:
            for fn in [int(c["register"], 16)] + [int(v, 16) for v in c["slots"].values()]:
                owners[fn].add("engine/" + c["class"])
    if os.path.exists(REGISTRIES):
        for fam in json.load(open(REGISTRIES))["families"]:
            path = "game/" + FAMILY_FOLDER.get(fam["name"], fam["name"].lower())
            for t in fam["types"]:
                fns = [int(t["register"], 16)] + [int(v, 16) for v in t["slots"].values()]
                for fn in fns:
                    owners[fn].add((path, t["type"]))
    for fn, who in owners.items():
        if len(who) == 1 and fn not in out:
            w = next(iter(who))
            out[fn] = w if isinstance(w, str) else w[0]
    return out


def layout():
    """File lines: runs of functions of one known subject, the unknown ones
    between two runs of the same subject joining them (the linker lays out an
    object's functions together); unknown runs between different subjects go
    to game/unsorted, which noise_report.py counts."""
    funcs = sorted(int(f["start"], 16) for f in json.load(open(FUNCS)))
    known = subjects()
    labels = [known.get(a) for a in funcs]
    # fill unknowns between two equal labels
    i = 0
    while i < len(labels):
        if labels[i] is None:
            j = i
            while j < len(labels) and labels[j] is None:
                j += 1
            before = labels[i - 1] if i else None
            after = labels[j] if j < len(labels) else None
            fill = before if before is not None and before == after else "game/unsorted"
            for k in range(i, j):
                labels[k] = fill
            i = j
        else:
            i += 1
    out, last = [], None
    for a, lab in zip(funcs, labels):
        if lab != last:
            out.append((a, lab))
            last = lab
    notes = {
        "xdk/d3d8": "the XDK's Direct3D 8 (d3d8.lib), as the game linked it",
        "xdk/dsound": "the XDK's DirectSound (dsound.lib)",
        "xdk/xapi_usb": "the XDK's XAPI: the USB host driver, the pads and the memory units",
        "xdk/xapi": "the XDK's XAPI: files, threads, memory, saves, the title's start",
        "xdk/crt": "the C runtime (libcmt.lib)",
        "game/unsorted": "the game's code whose subject is not known yet",
        "engine/objects": "the engine's object system: classes, handles, and creating, releasing, cloning and"
                          " loading objects through their classes' callbacks",
    }
    lines = []
    seen = set()
    for a, lab in out:
        note = ""
        if lab not in seen:
            seen.add(lab)
            if lab in notes:
                note = notes[lab]
            elif lab.startswith("engine/"):
                note = "the engine's %s class: its registration and callbacks" % lab.split("/")[1]
            elif lab.startswith("game/"):
                note = "the game's %s, by type" % lab.split("/")[1].replace("_", " ")
            elif lab.startswith("bink/"):
                note = "RAD's Bink video codec (%s)" % lab.split("/")[1]
        lines.append(line(a, "file", lab, note))
    sections = parse()
    replace_section(sections, "source files (generated by tools/symbols.py layout from what is known of "
                    "each function's subject)", lines)
    # the file section first, after the header
    sections = [sections[0]] + [s for s in sections[1:] if s[0] and s[0].startswith("source files")] + \
               [s for s in sections[1:] if not (s[0] and s[0].startswith("source files"))]
    write(sections)
    count = collections.Counter(labels)
    print("laid out %d functions in %d files (%d stretches); game/unsorted holds %d" %
          (len(funcs), len(count), len(out), count.get("game/unsorted", 0)))


# ── header: the structures and variables for the C written by hand ─

HEADER_OUT = os.path.join(REPO, "src", "recomp", "gen", "symbols.h")


def header():
    """src/recomp/gen/symbols.h: for each structure its size and an accessor
    per field, NAME_field(p), the field of the structure at guest address p
    (pointers in the guest's structures are guest addresses: a u32 that
    points at a struct says which in a comment); for each variable its
    address and an accessor, NAME or NAME(i) for an array; for each data line
    its address, NAME_VA; for each field its guest address too,
    STRUCT_FIELD_VA(p), and for each function its address, NAME_VA, for C
    written by hand that hands one to the game's code. Structures are read in place in the guest's memory,
    so no layout is invented for the bytes nobody has named."""
    sym = load()
    out = ["/**",
           " *    Name:        symbols.h",
           " *    Description: the game's structures and variables, by name, for the C written by hand",
           " *",
           " *    Generated by tools/symbols.py header from symbols/symbols.txt. Not edited by hand.",
           " */",
           "#ifndef ROBOTECH_SYMBOLS_H",
           "#define ROBOTECH_SYMBOLS_H",
           ""]
    problems = []
    for name, st in sorted(sym["structs"].items()):
        out.append("/* %s (0x%X bytes)%s */" % (name, st.get("size", 0), (": " + st["note"]) if st.get("note") else ""))
        out.append("#define %s_SIZE 0x%Xu" % (name, st.get("size", 0)))
        for fld in sorted(st["fields"], key=lambda f: f["offset"]):
            m = TYPE_RE.match(fld["type"])
            ctype, count = TYPES[m.group(1)], m.group(2)
            if st.get("size") and fld["offset"] >= st["size"]:
                problems.append("%s.%s at 0x%X is past its size" % (name, fld["name"], fld["offset"]))
            what = fld["note"] or ""
            if fld["points"]:
                what = ("points at a %s" % fld["points"]) + ("; " + what if what else "")
            if what:
                out.append("/*   %s */" % what)
            if count is None:
                out.append("#define %s_%s(p) (*(volatile %s *)XBOX_PTR((uint32_t)(p) + 0x%Xu))"
                           % (name, fld["name"], ctype, fld["offset"]))
            else:
                out.append("#define %s_%s(p) ((volatile %s *)XBOX_PTR((uint32_t)(p) + 0x%Xu))"
                           % (name, fld["name"], ctype, fld["offset"]))
            # its guest address, for handing it to the game's code
            out.append("#define %s_%s_VA(p) ((uint32_t)(p) + 0x%Xu)" % (name, fld["name"], fld["offset"]))
        out.append("")
    for addr, v in sorted(sym["vars"].items()):
        m = TYPE_RE.match(v["type"])
        ctype, count = TYPES[m.group(1)], m.group(2)
        what = v["note"] or ""
        if v["points"]:
            what = ("points at a %s" % v["points"]) + ("; " + what if what else "")
        if what:
            out.append("/* %s */" % what)
        out.append("#define %s_VA 0x%08Xu" % (v["name"], addr))
        if count is None:
            out.append("#define %s (*(volatile %s *)XBOX_PTR(%s_VA))" % (v["name"], ctype, v["name"]))
        else:
            out.append("#define %s(i) (((volatile %s *)XBOX_PTR(%s_VA))[i])" % (v["name"], ctype, v["name"]))
    out.append("")
    for addr, name in sorted(sym["data"].items()):
        if addr not in sym["vars"]:
            out.append("#define %s_VA 0x%08Xu" % (name, addr))
    # the functions' addresses, for C written by hand that hands one to the
    # game (a callback) or compares one
    out.append("")
    for addr, name in sorted(sym["func"].items()):
        out.append("#define %s_VA 0x%08Xu" % (name, addr))
    out += ["", "#endif", ""]
    os.makedirs(os.path.dirname(HEADER_OUT), exist_ok=True)
    with open(HEADER_OUT, "w", encoding="utf-8", newline="\n") as f:
        f.write("\n".join(out))
    print("symbols.h: %d structures, %d fields, %d variables, %d data addresses"
          % (len(sym["structs"]), sum(len(s["fields"]) for s in sym["structs"].values()), len(sym["vars"]),
             len(sym["data"]) - len(sym["vars"])))
    for p_ in problems:
        print("  " + p_)


def main():
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("command", choices=["merge", "layout", "header"])
    ap.add_argument("--toolkit", default=os.path.join(os.path.dirname(REPO), "xboxrecomp"))
    args = ap.parse_args()
    if args.command == "merge":
        merge(args.toolkit)
    elif args.command == "layout":
        layout()
    else:
        header()


if __name__ == "__main__":
    main()
