"""Puts a side session's proposal of symbol lines into symbols/symbols.txt, its renames everywhere.

    py -3.14 tools/apply_proposal.py PROPOSAL "TITLE"            what it would do, writing nothing
    py -3.14 tools/apply_proposal.py PROPOSAL "TITLE" --write    does it

A proposal (build/sessions/*/proposal.txt) is lines in symbols.txt's own syntax plus
`rename OLD NEW  # 0xADDRESS: why`, and `retype FAMILY NUMBER NAME` is not needed: a `type` line for a
type that has a name already takes the place of that line. tools/weapons_check_proposal.py checks a
proposal before this runs; this does what it says:

- each rename: the `func` line of OLD (at the address the comment gives, or it stops) gets NEW, and OLD
  becomes NEW in every line of symbols.txt (comments, `comment`, `param` and `local` lines) and in the C
  written by hand (src/game, src/*.c), as a whole word or as the prefix of a type's function
  (OLD_Register). A type whose name changes (a `type` line that replaces another's) is renamed the same
  way, every rename at once, so a swap of two names is one step;
- the proposal's other lines go into a section of their own, TITLE, before the naming waves', with the
  functions' renames applied to them too (a proposal writes today's names, and some of them it renames;
  a type it renames it already calls by the new name, and a swap gives the old one to another), but for a
  `type` line, a `comment` of a name that has one by hand, a `struct` declared already and a field at an
  offset its struct has one, which take the place of the line they meet (a field whose name or type
  changes is printed: tools/cross_proposals.py first, so that two lanes do not undo each other).

Last, with --write, the functions only a newly named type has lose the name a naming wave's model gave
them (drop_model_names), so that `symbols.py merge`, to run after this, gives them the type's.

Every change is printed; with --write it is made. The decompiled C is rewritten by the build.
"""
import os
import re
import sys

REPO = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
SYM = os.path.join(REPO, "symbols", "symbols.txt")
HAND_C = [os.path.join(REPO, "src", "game"), os.path.join(REPO, "src")]
BEFORE = "# ======== functions named from their decompiled C (w1;"
ADDR = re.compile(r"^[0-9A-Fa-f]{8}$")


def hand_c_files():
    for d in HAND_C:
        if not os.path.isdir(d):
            continue
        for f in sorted(os.listdir(d)):
            if f.endswith((".c", ".h", ".cpp")):
                yield os.path.join(d, f)


def main():
    if len(sys.argv) < 3:
        sys.exit(__doc__)
    prop, title, write = sys.argv[1], sys.argv[2], "--write" in sys.argv
    lines = open(SYM, encoding="utf-8").read().split("\n")
    funcs = {}                                   # name: (index, address)
    types = {}                                   # (family, number): (index, name)
    comments, structs, fields = {}, {}, {}       # name: index; struct: (index, size); (struct, offset): index
    variables = {}                               # address: (index, name)
    params = {}                                  # (function, register): index
    generated = False
    for i, l in enumerate(lines):
        if l.startswith("# ========"):
            generated = "(generated by" in l
        f = l.partition("#")[0].split()
        if len(f) >= 3 and ADDR.match(f[0]) and f[1] == "func":
            funcs.setdefault(f[2], (i, int(f[0], 16)))
        elif len(f) == 4 and f[0] == "type" and f[2].isdigit():
            types[(f[1], int(f[2]))] = (i, f[3])
        elif len(f) >= 3 and f[0] == "comment" and not generated:
            comments[f[1]] = i
        elif len(f) >= 4 and ADDR.match(f[0]) and f[1] == "var":
            variables[int(f[0], 16)] = (i, f[2])
        elif len(f) == 4 and f[0] == "param":
            params[(f[1], f[2])] = i
        elif len(f) == 3 and f[0] == "struct":
            structs[f[1]] = (i, int(f[2], 16))
        elif len(f) >= 5 and f[0] == "field":
            fields[(f[1], int(f[2], 16))] = i

    renames, problems, new, retyped = {}, [], [], set()
    for n, l in enumerate(open(prop, encoding="utf-8").read().split("\n"), 1):
        f = l.partition("#")[0].split()
        if not f:
            continue
        if f[0] == "rename":
            old, nw = f[1], f[2]
            # the first address of the comment, 0x45370 or 00045370
            m = re.search(r"0x([0-9A-Fa-f]+)|\b([0-9A-Fa-f]{8})\b", l.partition("#")[2])
            if old not in funcs:
                problems.append("line %d: rename %s: no such function" % (n, old))
            elif not m or int(m.group(1) or m.group(2), 16) != funcs[old][1]:
                problems.append("line %d: rename %s: it is at 0x%X, not %s" % (n, old, funcs[old][1], m and m.group(0)))
            else:
                renames[old] = nw
            continue
        if f[0] == "type" and len(f) >= 4 and (f[1], int(f[2])) in types and types[(f[1], int(f[2]))][1] != f[3]:
            renames[types[(f[1], int(f[2]))][1]] = f[3]
            retyped.add(types[(f[1], int(f[2]))][1])
        if len(f) >= 4 and ADDR.match(f[0]) and f[1] == "var" and int(f[0], 16) in variables and \
                variables[int(f[0], 16)][1] != f[2]:
            renames[variables[int(f[0], 16)][1]] = f[2]
            retyped.add(variables[int(f[0], 16)][1])
        new.append((n, l))
    if problems:
        sys.exit("\n".join(problems))

    word = re.compile(r"\b(%s)(?=\b|_)" % "|".join(sorted(map(re.escape, renames), key=len, reverse=True)))
    sub = lambda s: word.sub(lambda m: renames[m.group(1)], s) if renames else s
    comments = {sub(name): i for name, i in comments.items()}   # a renamed function's comment by its new name
    params = {(sub(function), reg): i for (function, reg), i in params.items()}
    # the proposal's own lines name a renamed type by its new name already (a swap gives the old name to another)
    # and a name that one rename gives up and another takes, it means as the one that takes it
    keep = retyped | (set(renames) & set(renames.values()))
    sub_new = lambda s: word.sub(lambda m: m.group(1) if m.group(1) in keep else renames[m.group(1)], s) if renames else s

    changed = 0
    for i, l in enumerate(lines):
        if l.startswith("# ========") and "(generated by" in l:
            continue
        s = sub(l)
        if s != l:
            changed += 1
            lines[i] = s
    print("symbols.txt: %d lines with a renamed name" % changed)
    for path in hand_c_files():
        text = open(path, encoding="utf-8", errors="surrogateescape").read()
        s = sub(text)
        if s != text:
            print("  %s: %d names" % (os.path.relpath(path, REPO), len(word.findall(text))))
            if write:
                open(path, "w", encoding="utf-8", errors="surrogateescape", newline="").write(s)

    section = []
    for n, l in new:
        s = sub_new(l)
        if s != l:
            print("  proposal line %d: %s" % (n, ", ".join(sorted(set(word.findall(l)) - keep))))
        f = s.partition("#")[0].split()
        if f[0] == "type" and len(f) >= 4 and (f[1], int(f[2])) in types:
            lines[types[(f[1], int(f[2]))][0]] = l
            print("  type %s %s: in place of the line there" % (f[1], f[2]))
        elif len(f) >= 4 and ADDR.match(f[0]) and f[1] == "var" and int(f[0], 16) in variables:
            lines[variables[int(f[0], 16)][0]] = s
            print("  var %s: in place of the line there" % f[0])
        elif f[0] == "param" and len(f) == 4 and (f[1], f[2]) in params:
            lines[params[(f[1], f[2])]] = s
            print("  param %s %s: in place of the line there" % (f[1], f[2]))
        elif f[0] == "comment" and f[1] in comments:
            lines[comments[f[1]]] = s
            print("  comment %s: in place of the one by hand" % f[1])
        elif len(f) >= 3 and ADDR.match(f[0]) and f[1] == "func" and funcs.get(f[2], (0, -1))[1] == int(f[0], 16):
            pass                                 # symbols.txt names it so already (another lane's line)
        elif f[0] == "struct" and f[1] in structs:
            i, size = structs[f[1]]
            if int(f[2], 16) != size:
                print("  struct %s: size %s here, 0x%X in symbols.txt: the bigger one kept" % (f[1], f[2], size))
                if int(f[2], 16) > size:
                    lines[i] = s
        elif f[0] == "field" and (f[1], int(f[2], 16)) in fields:
            i = fields[(f[1], int(f[2], 16))]
            if lines[i].partition("#")[0].split()[3:] != f[3:]:
                print("  field %s +0x%s: %s in place of %s" % (f[1], f[2], " ".join(f[3:]),
                                                          " ".join(lines[i].partition("#")[0].split()[3:])))
            lines[i] = s
        else:
            section.append(s)
    at = next(i for i, l in enumerate(lines) if l.startswith(BEFORE))
    while at > 0 and lines[at - 1] == "":
        at -= 1
    if section:                                  # a proposal of renames alone needs no section
        lines[at:at] = ["", "# ======== %s ========" % title] + section
    print("%d renames, %d new lines in the section" % (len(renames), len(section)))
    if write:
        open(SYM, "w", encoding="utf-8", newline="\n").write("\n".join(lines))
        new_types = {(f[1], int(f[2])) for f in (l.partition("#")[0].split() for _, l in new)
                     if len(f) >= 4 and f[0] == "type" and f[2].isdigit()}
        drop_model_names(new_types)


def drop_model_names(new_types):
    """The functions only one of new_types has, named by a naming wave's model, lose that name (their func
    and comment lines), and every mention of it becomes the type's (NAME_Startup...), which `symbols.py
    merge` then writes: a type's own name wins over a model's guess at the function."""
    import collections
    import json
    sys.path.insert(0, os.path.join(REPO, "tools"))
    import symbols as S
    sym = S.load()
    users = collections.defaultdict(list)
    for fam in json.load(open(S.REGISTRIES))["families"]:
        for t in fam["types"]:
            users[int(t["register"], 16)].append((fam["name"], t["type"], "Register"))
            for off, va in t["slots"].items():
                if off in S.TYPE_SLOTS:
                    users[int(va, 16)].append((fam["name"], t["type"], S.TYPE_SLOTS[off]))
    waves = set()
    for title, body in S.parse():
        if title and title.startswith("functions named from their decompiled C"):
            waves |= {e["address"] for e in S.entries(body) if e["kind"] == "func"}
    ren = {sym["func"][fn]: "%s_%s" % (sym["types"][us[0][:2]][0], us[0][2]) for fn, us in users.items()
           if len(us) == 1 and us[0][:2] in new_types and fn in waves}
    ren = {old: new for old, new in ren.items() if old != new}   # a proposal's rename gave it the type's name already
    if not ren:
        return
    word = re.compile(r"\b(%s)\b" % "|".join(map(re.escape, ren)))
    out, generated, dropped = [], False, 0
    for l in open(SYM, encoding="utf-8").read().split("\n"):
        if l.startswith("# ========"):
            generated = "(generated by" in l
        f = l.partition("#")[0].split()
        if not generated and ((len(f) >= 3 and ADDR.match(f[0]) and f[1] == "func" and f[2] in ren) or
                              (len(f) >= 2 and f[0] == "comment" and f[1] in ren)):
            dropped += 1
            continue
        out.append(word.sub(lambda m: ren[m.group(1)], l))
    open(SYM, "w", encoding="utf-8", newline="\n").write("\n".join(out))
    for path in hand_c_files():
        text = open(path, encoding="utf-8", errors="surrogateescape").read()
        if word.search(text):
            open(path, "w", encoding="utf-8", errors="surrogateescape", newline="").write(
                word.sub(lambda m: ren[m.group(1)], text))
            print("  %s: a model's name of a type's function" % os.path.relpath(path, REPO))
    print("%d functions of the new types take the type's name in place of a model's (%d lines dropped); "
          "run symbols.py merge" % (len(ren), dropped))


if __name__ == "__main__":
    main()
